/**
 * Shared harness for the accessibility tests.
 *
 * Runs axe-core over a real, rendered piece of the app and fails with a
 * readable summary of any violation. The suites that use it build their DOM
 * from the actual modules (`initApp`, the renderers) rather than from fixture
 * HTML, so a regression in the markup is what breaks the test.
 *
 * **Scope.** jsdom has no layout engine, so rules that need geometry or
 * painted pixels cannot run — `color-contrast` above all. Those stay a manual
 * check (see the contrast notes in `src/style.css`). What this does cover is
 * the structural half: accessible names, label/control association, ARIA
 * validity, landmark and heading structure, duplicate ids.
 */
import axe from "axe-core";
import { expect, vi } from "vitest";
import { readFileSync } from "node:fs";
import { FIXTURE_PATH } from "../alt-text/helpers";

/** Rules axe cannot evaluate without layout; running them only yields noise. */
const DISABLED_RULES = ["color-contrast"];

export interface AxeOptions {
  /** Extra rule ids to switch off, with a reason in the caller's comment. */
  disable?: string[];
}

/**
 * Assert that `element` has no axe violations. The element must already be
 * attached to `document`, which is how axe resolves inherited state.
 */
export async function expectNoViolations(
  element: Element,
  options: AxeOptions = {}
): Promise<void> {
  const rules: Record<string, { enabled: false }> = {};
  for (const id of [...DISABLED_RULES, ...(options.disable ?? [])]) {
    rules[id] = { enabled: false };
  }

  const results = await axe.run(element as HTMLElement, {
    rules,
    // The report's own <h1> lives inside a step whose heading is an <h2>.
    // That is intentional and documented — see the <article> comment in
    // src/app.ts — and axe's heading-order only flags downward skips anyway.
    resultTypes: ["violations"],
  });

  if (results.violations.length > 0) {
    throw new Error(formatViolations(results.violations));
  }
  expect(results.violations).toHaveLength(0);
}

function formatViolations(violations: axe.Result[]): string {
  return [
    `${violations.length} accessibility violation(s):`,
    ...violations.map((v) => {
      const targets = v.nodes
        .slice(0, 4)
        .map((n) => `      - ${String(n.target[0])}\n        ${n.failureSummary?.replace(/\n/g, "\n        ")}`)
        .join("\n");
      const more = v.nodes.length > 4 ? `\n      … and ${v.nodes.length - 4} more` : "";
      return `  [${v.impact}] ${v.id}: ${v.help}\n${targets}${more}`;
    }),
  ].join("\n");
}

/**
 * Mount a fresh `#app` root in the document body and return it. Each suite
 * gets a clean document so ids generated by the info module and the mapping
 * UI cannot collide across tests.
 */
export function mountRoot(): HTMLElement {
  document.body.innerHTML = "";
  const root = document.createElement("div");
  root.id = "app";
  document.body.appendChild(root);
  return root;
}

// ── Driving the workflow ─────────────────────────────────────────────
// The same clicks a user makes, so the DOM under test is the one `initApp`
// really builds at each step.

/** Walk from the template step to the data step. */
export function goToDataStep(root: HTMLElement): void {
  root.querySelector<HTMLButtonElement>("#template-continue")!.click();
}

/** Press the mapping panel's Continue, opening the data-validation step. */
export function continueFromData(root: HTMLElement): void {
  root.querySelectorAll<HTMLButtonElement>(".data-mapping-panel > button")[0].click();
}

/** Press the data-validation step's Continue, opening the parameters step. */
export function continueFromValidation(root: HTMLElement): void {
  root.querySelector<HTMLButtonElement>("#validation-container > button")!.click();
}

/**
 * Walk on to the data-validation step. No file is uploaded: the mapping step
 * is deliberately non-blocking, so Continue proceeds with unmapped sheets and
 * surfaces warnings — which is itself a state worth checking.
 */
export function goToValidationStep(root: HTMLElement): void {
  goToDataStep(root);
  continueFromData(root);
}

/** …and on to the parameters step. */
export function goToParamsStep(root: HTMLElement): void {
  goToValidationStep(root);
  continueFromValidation(root);
}

/**
 * Put `file` on a file input and fire `change`, as a real pick would.
 * `files` is read-only in jsdom, hence the property override.
 */
export function pickFile(input: HTMLInputElement, file: File): void {
  Object.defineProperty(input, "files", { value: [file], configurable: true });
  input.dispatchEvent(new Event("change"));
}

/**
 * Upload the `dummy.xlsx` fixture to every workbook input of the data step
 * (XLSX mode) and wait until each has been parsed — the change handler is
 * async. The fixture's sheet and column names match the config, so the
 * mapping UI pre-selects them all, exactly as for a user with a clean export.
 */
export async function uploadFixture(root: HTMLElement): Promise<void> {
  const bytes = readFileSync(FIXTURE_PATH);
  const inputs = root.querySelectorAll<HTMLInputElement>('.data-mapping input[type="file"]');
  expect(inputs.length).toBeGreaterThan(0);
  for (const input of inputs) pickFile(input, new File([bytes], "dummy.xlsx"));

  await vi.waitFor(() => {
    for (const error of root.querySelectorAll(".upload-error")) {
      expect(error.textContent, "fixture upload was rejected").toBe("");
    }
    const sheetSelects = [...root.querySelectorAll<HTMLSelectElement>(".sheet-map select")];
    expect(sheetSelects.some((s) => s.value !== "")).toBe(true);
  });
}
